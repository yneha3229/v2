"""U7 exception desk (D21) and U8 founder email draft (D22).

The service runs end to end; a person is needed only for what this module lists.
Both functions read a finished CaseRecord and never call any API.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass

from proofroom.models import CaseRecord

# Ordered by how urgently a person must look.
KINDS = ("identity", "conflict", "suppressed", "check_incomplete", "retrieval")


@dataclass
class ExceptionItem:
    kind: str          # one of KINDS
    title: str
    detail: str
    evidence_ids: list[str]

    def as_dict(self) -> dict:
        return asdict(self)


def exception_desk(case: CaseRecord) -> list[ExceptionItem]:
    """Everything that needs a person, most urgent first. Empty means the run needs none."""
    items: list[ExceptionItem] = []
    g1 = case.g1 or {}
    status = g1.get("status")
    if status == "TIE":
        names = ", ".join(f"{c.get('name')} ({c.get('id')})" for c in g1.get("candidates", []))
        items.append(ExceptionItem("identity", "Which company is this?",
                                   f"{g1.get('basis', '')}. Candidates: {names}", []))
    elif status == "NO_MATCH":
        items.append(ExceptionItem("identity", "Company not found in Crustdata's graph",
                                   f"{g1.get('basis', '')}. Company-dependent claims are "
                                   "not established.", []))

    for f in case.findings:
        if f.disposition == "conflicting":
            items.append(ExceptionItem("conflict", f"{f.claim_id}: sources disagree",
                                       f.sentence, list(f.evidence_ids)))

    for lim in case.limitations:
        low = lim.lower()
        if "suppressed" in low:
            items.append(ExceptionItem("suppressed", "A sentence was withheld", lim, []))
        elif "check incomplete" in low or "unchecked" in low:
            items.append(ExceptionItem("check_incomplete", "A check did not finish", lim, []))
        elif "failed" in low and ("fetch" in low or "crustdata" in low or "lookup" in low
                                  or "enrich" in low or "discovery" in low):
            items.append(ExceptionItem("retrieval", "A data source failed", lim, []))

    order = {k: i for i, k in enumerate(KINDS)}
    return sorted(items, key=lambda it: order.get(it.kind, len(KINDS)))


def exception_desk_md(items: list[ExceptionItem]) -> str:
    if not items:
        return "**Needs a person: 0.** Every selected claim finished its checks.\n"
    lines = [f"**Needs a person: {len(items)}**", ""]
    for it in items:
        cites = "".join(f"[{e}]" for e in it.evidence_ids)
        lines.append(f"- **{it.title}** ({it.kind}): {it.detail} {cites}".rstrip())
    return "\n".join(lines) + "\n"


def founder_email_md(case: CaseRecord, *, sender: str = "‹your name›") -> str:
    """U8: a polite draft to the founder carrying the brief's questions. Draft only;
    Proofroom never sends anything (deck rule: agents contact only the team)."""
    company = (case.g1 or {}).get("name") or case.input.domain
    founders = [t.name for t in case.team if t.role_join][:3]
    greeting = "Hi " + (" and ".join(n.split()[0] for n in founders) if founders else "there")
    questions = list(dict.fromkeys(q.strip() for q in case.questions if q.strip()))
    body = [
        "<!-- DRAFT generated by Proofroom. Not sent. Review before use. -->",
        f"**Subject:** A few questions before our meeting about {company}",
        "",
        f"{greeting},",
        "",
        f"Thank you for making time to talk about {company}. While preparing, we read your "
        "announcement and the public record, and a few points would help us get the details "
        "right:",
        "",
    ]
    if questions:
        body += [f"{i}. {q}" for i, q in enumerate(questions[:6], 1)]
    else:
        body.append("1. Is there anything about the team or the financing history that the "
                    "public sources leave out?")
    body += ["", "Happy to cover these in the meeting if that is easier.", "", "Best,",
             sender, ""]
    return "\n".join(body)
